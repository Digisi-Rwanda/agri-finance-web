const portalByLocale = {
  en: portalCopyEn,
  fr: mergeCopy(portalCopyEn, portalFr),
  rw: mergeCopy(portalCopyEn, portalRw),
}
export function getPortalCopy(locale) {
  return portalByLocale[locale] || portalByLocale.en
}

export function roleLabel(portal, roleCode) {
  return portal.roles[roleCode] || roleCode
}

export function partnerRoleLabel(portal, roleCode) {
  return portal.adminUsers.partnerRoles[roleCode] || portal.roles[roleCode] || roleCode
}
