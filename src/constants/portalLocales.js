function mergeCopy(base, overrides) {
  if (!overrides) return base
  if (Array.isArray(base)) return overrides
  if (typeof base !== 'object' || base === null) return overrides ?? base
  const out = { ...base }
  for (const key of Object.keys(overrides)) {
    const b = base[key]
    const o = overrides[key]
    if (o && typeof o === 'object' && !Array.isArray(o) && typeof b === 'object' && b !== null && !Array.isArray(b)) {
      out[key] = mergeCopy(b, o)
    } else {
      out[key] = o
    }
  }
  return out
}

